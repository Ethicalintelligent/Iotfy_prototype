CREATE TABLE IF NOT EXISTS gps.company (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id      uuid         NOT NULL UNIQUE,
    created_at     timestamptz  NOT NULL DEFAULT now(),
    name           varchar(200) NOT NULL,
    legal_name     varchar(200),
    status         varchar(16)  NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'SUSPENDED')),
    timezone       varchar(64)  NOT NULL DEFAULT 'UTC',
    country_code   char(2),
    retention_days integer      NOT NULL DEFAULT 90 CHECK (retention_days IN (30, 90, 180)),
    legacy_id      varchar(50),
    updated_at     timestamptz  NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS gps.branch (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id bigint       NOT NULL REFERENCES gps.company (id),
    parent_id  bigint       REFERENCES gps.branch (id),
    code       varchar(40),
    name       varchar(120) NOT NULL,
    location   varchar(200),
    created_at timestamptz  NOT NULL DEFAULT now(),
    UNIQUE (company_id, name)
);

CREATE TABLE IF NOT EXISTS gps.asset_group (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id     uuid         NOT NULL UNIQUE,
    created_at    timestamptz  NOT NULL DEFAULT now(),
    company_id    bigint       NOT NULL REFERENCES gps.company (id),
    parent_id     bigint       REFERENCES gps.asset_group (id),
    solution_code varchar(32)  REFERENCES gps.solution (code),
    name          varchar(120) NOT NULL,
    description   varchar(300),
    color         varchar(16),
    image_url     varchar(500),
    created_by    bigint
);
CREATE INDEX IF NOT EXISTS asset_group_company ON gps.asset_group (company_id, parent_id);

CREATE TABLE IF NOT EXISTS gps.app_user (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id           uuid         NOT NULL UNIQUE,
    created_at          timestamptz  NOT NULL DEFAULT now(),
    company_id          bigint       REFERENCES gps.company (id),
    user_type           varchar(16)  NOT NULL CHECK (user_type IN ('SUPER_ADMIN', 'COMPANY_ADMIN', 'USER')),
    email               varchar(254) NOT NULL,
    name                varchar(200) NOT NULL,
    mobile              varchar(30),
    password_hash       varchar(100) NOT NULL,
    status              varchar(16)  NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'DISABLED')),
    mfa_secret          varchar(255),
    mfa_enabled         boolean      NOT NULL DEFAULT false,
    password_changed_at timestamptz  NOT NULL DEFAULT now(),
    legacy_id           varchar(50),
    CHECK ((user_type = 'SUPER_ADMIN') = (company_id IS NULL))
);
CREATE UNIQUE INDEX IF NOT EXISTS app_user_email ON gps.app_user (lower(email));
CREATE INDEX IF NOT EXISTS app_user_company ON gps.app_user (company_id);

CREATE TABLE IF NOT EXISTS gps.device_protocol (
    code                  varchar(32) PRIMARY KEY,
    listening_port        integer,
    packet_size           integer,
    read_timeout_s        integer,
    validate_first_packet boolean     NOT NULL DEFAULT true,
    mirror_host           varchar(100),
    mirror_port           integer
);

CREATE TABLE IF NOT EXISTS gps.device_manufacturer (
    id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     varchar(100) NOT NULL UNIQUE,
    location varchar(200),
    website  varchar(300)
);

CREATE TABLE IF NOT EXISTS gps.device_model (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    manufacturer_id   bigint       NOT NULL REFERENCES gps.device_manufacturer (id),
    name              varchar(100) NOT NULL,
    protocol_code     varchar(32)  NOT NULL REFERENCES gps.device_protocol (code),
    device_type       varchar(32)  NOT NULL DEFAULT 'VEHICLE_TRACKER'
                      CHECK (device_type IN ('VEHICLE_TRACKER', 'PERSONAL_TRACKER', 'MOBILE_APP', 'OBD', 'OTHER')),
    transport         varchar(8)   NOT NULL DEFAULT 'TCP' CHECK (transport IN ('TCP', 'UDP', 'HTTP', 'MQTT')),
    supports_geofence boolean      NOT NULL DEFAULT false,
    default_io_map    jsonb        NOT NULL DEFAULT '{}',
    UNIQUE (manufacturer_id, name)
);

CREATE TABLE IF NOT EXISTS gps.sim_card (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id     uuid         NOT NULL UNIQUE,
    created_at    timestamptz  NOT NULL DEFAULT now(),
    company_id    bigint       NOT NULL REFERENCES gps.company (id),
    iccid         varchar(255) NOT NULL,
    msisdn        varchar(255),
    serial_no     varchar(60),
    provider      varchar(100),
    plan          varchar(100),
    pin_code      varchar(255),
    puk_code      varchar(255),
    support_no    varchar(30),
    purchase_date date,
    expiry_date   date,
    reminder_days integer,
    installer_id  bigint,
    status        varchar(16)  NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE', 'SUSPENDED')),
    updated_by    bigint,
    updated_at    timestamptz  NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS gps.device (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id             uuid        NOT NULL UNIQUE,
    created_at            timestamptz NOT NULL DEFAULT now(),
    company_id            bigint      NOT NULL REFERENCES gps.company (id),
    imei                  varchar(20) NOT NULL UNIQUE,
    protocol              varchar(32) NOT NULL,
    model                 varchar(100),
    model_id              bigint      REFERENCES gps.device_model (id),
    sim_card_id           bigint      UNIQUE REFERENCES gps.sim_card (id),
    secondary_sim_card_id bigint      UNIQUE REFERENCES gps.sim_card (id),
    serial_no             varchar(60),
    firmware_version      varchar(40),
    purchase_date         date,
    warranty_expiry       date,
    additional_warranty   date,
    certificate_details   varchar(300),
    reminder_days         integer,
    installer_id          bigint,
    io_config             jsonb       NOT NULL DEFAULT '{}',
    modbus_config         jsonb,
    status                varchar(16) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE', 'FAULTY', 'IN_STOCK')),
    updated_by            bigint,
    updated_at            timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS device_company ON gps.device (company_id);

CREATE TABLE IF NOT EXISTS gps.tracked_asset (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id     uuid         NOT NULL UNIQUE,
    created_at    timestamptz  NOT NULL DEFAULT now(),
    company_id    bigint       NOT NULL REFERENCES gps.company (id),
    asset_type    varchar(32)  NOT NULL,
    code          varchar(60),
    name          varchar(200) NOT NULL,
    branch_id     bigint       REFERENCES gps.branch (id),
    group_id      bigint       REFERENCES gps.asset_group (id),
    icon_url      varchar(500),
    image_url     varchar(500),
    reference_key varchar(60),
    tags          text[]       NOT NULL DEFAULT '{}',
    remark        varchar(500),
    asset_info    jsonb        NOT NULL DEFAULT '{}',
    watch_mode    boolean      NOT NULL DEFAULT false,
    rest_days     varchar(27),
    status        varchar(16)  NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE')),
    created_by    bigint,
    updated_by    bigint,
    updated_at    timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS tracked_asset_company ON gps.tracked_asset (company_id, asset_type);
CREATE UNIQUE INDEX IF NOT EXISTS tracked_asset_code ON gps.tracked_asset (company_id, asset_type, upper(code))
    WHERE code IS NOT NULL AND status = 'ACTIVE';
CREATE INDEX IF NOT EXISTS tracked_asset_tags ON gps.tracked_asset USING gin (tags);

