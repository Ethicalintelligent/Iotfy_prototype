    asset_id      bigint,
    ts            timestamptz      NOT NULL,
    received_at   timestamptz      NOT NULL DEFAULT now(),
    lat           double precision NOT NULL,
    lng           double precision NOT NULL,
    altitude_m    real,
    speed_kmh     real,
    heading_deg   smallint,
    satellites    smallint,
    hdop          real,
    gps_valid     boolean,
    gsm_signal    smallint,
    priority      smallint,
    event_code    integer,
    ignition      boolean,
    motion_state  varchar(20),
    odometer_m    bigint,
    engine_s      bigint,
    battery_mv    integer,
    ext_power_mv  integer,
    fuel_level    real,
    temp1 real, temp2 real, temp3 real, temp4 real,
    ai1 real, ai2 real, ai3 real, ai4 real,
    di_mask       smallint,
    do_mask       smallint,
    bytes_rx      integer,
    location_name varchar(300),
    io            jsonb,
    processed_io  jsonb,
    tags          text[],
    flags         integer          NOT NULL DEFAULT 0
);
