-- 012: alert ids are database-numbered (IT-0045, admin, 26 Nov 2026).
--   gps.alert_rules.id, telemetry.alerts.id, telemetry.alert_notifications.id: text -> bigint identity
--     (the database gives the next number; the app reserves ids with useNextIds).
--   Linked columns become bigint too: gps.alert_recipients.alert_rule_id, telemetry.alerts.alert_rule_id,
--     telemetry.alert_notifications.alert_id, gps.alert_tickets.alert_id, telemetry.dashcam_media.alert_id.
--   gps.alert_rules.asset_group: text -> bigint, now a link (foreign key) to core.asset_group.
-- Existing ids must be whole numbers (all tables were empty when this was written).
-- Run as the database owner. Safe to run again: each step checks whether it is already done.

BEGIN;

-- 1. Drop the links that point at the columns being changed (re-added in step 4).
ALTER TABLE gps.alert_recipients          DROP CONSTRAINT IF EXISTS alert_recipients_alert_rule_id_fkey;
ALTER TABLE telemetry.alerts              DROP CONSTRAINT IF EXISTS alerts_alert_rule_id_fkey;
ALTER TABLE telemetry.alert_notifications DROP CONSTRAINT IF EXISTS alert_notifications_alert_id_fkey;
ALTER TABLE gps.alert_tickets             DROP CONSTRAINT IF EXISTS alert_tickets_alert_id_fkey;
ALTER TABLE telemetry.dashcam_media       DROP CONSTRAINT IF EXISTS dashcam_media_alert_id_fkey;
ALTER TABLE gps.alert_rules               DROP CONSTRAINT IF EXISTS alert_rules_asset_group_fkey;

-- 2. Change the types (skipped when a column is already bigint).
DO $$
DECLARE c text[];
BEGIN
    FOREACH c SLICE 1 IN ARRAY ARRAY[
        ['gps',       'alert_rules',         'id'],
        ['gps',       'alert_rules',         'asset_group'],
        ['gps',       'alert_recipients',    'alert_rule_id'],
        ['telemetry', 'alerts',              'id'],
        ['telemetry', 'alerts',              'alert_rule_id'],
        ['telemetry', 'alert_notifications', 'id'],
        ['telemetry', 'alert_notifications', 'alert_id'],
        ['gps',       'alert_tickets',       'alert_id'],
        ['telemetry', 'dashcam_media',       'alert_id']
    ] LOOP
        IF EXISTS (SELECT 1 FROM information_schema.columns
                   WHERE table_schema = c[1] AND table_name = c[2] AND column_name = c[3]
                     AND data_type <> 'bigint') THEN
            EXECUTE format('ALTER TABLE %I.%I ALTER COLUMN %I TYPE bigint USING %I::bigint',
                           c[1], c[2], c[3], c[3]);
        END IF;
    END LOOP;
END $$;

-- 3. Let the database give the ids, starting after the highest existing one.
DO $$
DECLARE t text[];
BEGIN
    FOREACH t SLICE 1 IN ARRAY ARRAY[
        ['gps',       'alert_rules'],
        ['telemetry', 'alerts'],
        ['telemetry', 'alert_notifications']
    ] LOOP
        IF EXISTS (SELECT 1 FROM information_schema.columns
                   WHERE table_schema = t[1] AND table_name = t[2] AND column_name = 'id'
                     AND is_identity = 'NO') THEN
            EXECUTE format('ALTER TABLE %I.%I ALTER COLUMN id DROP DEFAULT', t[1], t[2]);
            EXECUTE format('ALTER TABLE %I.%I ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY', t[1], t[2]);
        END IF;
        EXECUTE format(
            'SELECT setval(pg_get_serial_sequence(%L, ''id''), coalesce(max(id), 0) + 1, false) FROM %I.%I',
            t[1] || '.' || t[2], t[1], t[2]);
    END LOOP;
END $$;

-- 4. Re-add the links with the same options as before, plus the new asset_group link.
ALTER TABLE gps.alert_recipients ADD CONSTRAINT alert_recipients_alert_rule_id_fkey
    FOREIGN KEY (alert_rule_id) REFERENCES gps.alert_rules(id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED;
ALTER TABLE telemetry.alerts ADD CONSTRAINT alerts_alert_rule_id_fkey
    FOREIGN KEY (alert_rule_id) REFERENCES gps.alert_rules(id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED;
ALTER TABLE telemetry.alert_notifications ADD CONSTRAINT alert_notifications_alert_id_fkey
    FOREIGN KEY (alert_id) REFERENCES telemetry.alerts(id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED;
ALTER TABLE gps.alert_tickets ADD CONSTRAINT alert_tickets_alert_id_fkey
    FOREIGN KEY (alert_id) REFERENCES telemetry.alerts(id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED;
ALTER TABLE telemetry.dashcam_media ADD CONSTRAINT dashcam_media_alert_id_fkey
    FOREIGN KEY (alert_id) REFERENCES telemetry.alerts(id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED;
ALTER TABLE gps.alert_rules ADD CONSTRAINT alert_rules_asset_group_fkey
    FOREIGN KEY (asset_group) REFERENCES core.asset_group(id) DEFERRABLE INITIALLY DEFERRED;

-- 5. The app reserves new ids with nextval (useNextIds), so its roles need the new sequences.
DO $$
DECLARE r text; s text;
BEGIN
    FOREACH s IN ARRAY ARRAY[
        pg_get_serial_sequence('gps.alert_rules', 'id'),
        pg_get_serial_sequence('telemetry.alerts', 'id'),
        pg_get_serial_sequence('telemetry.alert_notifications', 'id')
    ] LOOP
        FOREACH r IN ARRAY ARRAY['iotify_dev', 'iotify_prototyper', 'iotify_core_admin'] LOOP
            IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = r) THEN
                EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE %s TO %I', s, r);
            END IF;
        END LOOP;
    END LOOP;
END $$;

COMMIT;
