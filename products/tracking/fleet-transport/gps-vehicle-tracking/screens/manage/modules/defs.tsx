/** Operator dates must be in order (original `WD`). */
export function operatorDateErrors(v: Values): string[] {
  const t = (x: unknown) => (x == null ? '' : String(x).trim());
  const today = new Date().toISOString().slice(0, 10);
  const dob = t(v.dob);
  const doj = t(v.doj);
  const dol = t(v.dol);
  const out: string[] = [];
  if (dob && dob > today) out.push('Date of Birth cannot be in the future.');
  if (dob && doj && doj < dob) out.push('Date of Joining cannot be earlier than Date of Birth.');
  if (doj && dol && dol < doj) out.push('Date of Leaving cannot be earlier than Date of Joining.');
  return out;
}
