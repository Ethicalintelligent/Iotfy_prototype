// pnpm db:types: reads the `core` schema from Neon and writes
//   src/schema.gen.ts  (row types, table metadata, value lists from CHECK constraints)
//   src/hooks.gen.ts   (one hook per table, e.g. useAssets({ company_id }))
// Table and column names are kept exactly as in the database (snake_case). No renaming layer.
import fs from 'node:fs';
import path from 'node:path';
import { createRunner } from '../server/runner.js';

const here = import.meta.dirname;
const root = path.resolve(here, '..', '..', '..');
const envFile = path.join(root, '.env.local');
if (fs.existsSync(envFile)) process.loadEnvFile(envFile);
const url = (process.env.DATABASE_URL || '').trim();
if (!url) {
  console.error('DATABASE_URL is empty. Paste your Neon connection string into .env.local first.');
  process.exit(1);
}
const db = createRunner(url);

const columns = await db.query(`
  SELECT c.table_name, c.column_name, c.data_type, c.udt_name, c.is_nullable, c.column_default
  FROM information_schema.columns c
  JOIN information_schema.tables t ON t.table_schema = c.table_schema AND t.table_name = c.table_name
  WHERE c.table_schema = 'core' AND t.table_type = 'BASE TABLE'
  ORDER BY c.table_name, c.ordinal_position`);
const keys = await db.query(`
  SELECT tc.table_name, kcu.column_name
  FROM information_schema.table_constraints tc
  JOIN information_schema.key_column_usage kcu
    ON kcu.constraint_name = tc.constraint_name AND kcu.table_schema = tc.table_schema
  WHERE tc.table_schema = 'core' AND tc.constraint_type = 'PRIMARY KEY'
  ORDER BY tc.table_name, kcu.ordinal_position`);
const checks = await db.query(`
  SELECT cl.relname AS table_name, pg_get_constraintdef(co.oid) AS def
  FROM pg_constraint co
  JOIN pg_class cl ON cl.oid = co.conrelid
  JOIN pg_namespace n ON n.oid = cl.relnamespace
  WHERE n.nspname = 'core' AND co.contype = 'c'`);

// "CHECK ((type = ANY (ARRAY['Group'::text, 'Product'::text])))" → type: 'Group' | 'Product'
const enums = {};
for (const { table_name, def } of checks) {
  const m = def.match(
    /^CHECK \(\(\(?(\w+)\)?(?:::text)? = ANY \(\(?ARRAY\[(.+?)\]\)?(?:::text\[\])?\)\)\)$/,
  );
  if (!m) continue;
  const values = [...m[2].matchAll(/'((?:[^']|'')*)'/g)].map((v) => v[1].replace(/''/g, "'"));
  if (values.length) (enums[table_name] ??= {})[m[1]] = values;
}

const tsType = (c) => {
  switch (c.udt_name) {
    case 'bool':
      return 'boolean';
    case 'int2':
    case 'int4':
    case 'int8':
    case 'numeric':
    case 'float4':
    case 'float8':
      return 'number';
    case 'json':
    case 'jsonb':
      return 'unknown';
    default:
      return c.data_type === 'ARRAY' ? 'string[]' : 'string';
  }
};

const tables = {};
for (const c of columns) (tables[c.table_name] ??= { columns: [], pk: [] }).columns.push(c);
for (const k of keys) tables[k.table_name]?.pk.push(k.column_name);
const names = Object.keys(tables).sort();
const pascal = (s) => s.replace(/(^|_)([a-z0-9])/g, (_, __, ch) => ch.toUpperCase());
const q = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

let schema = `// GENERATED by \`pnpm db:types\` from Neon (schema core). Do not edit by hand.
// ${names.length} tables. Names match the database exactly (snake_case).

`;
for (const t of names) {
  const { columns: cols } = tables[t];
  schema += `export interface ${pascal(t)}Row {\n`;
  for (const c of cols) {
    const list = enums[t]?.[c.column_name];
    const type = list ? list.map(q).join(' | ') : tsType(c);
    const optional = c.column_default != null || c.is_nullable === 'YES';
    schema += `  ${c.column_name}${optional ? '?' : ''}: ${type}${c.is_nullable === 'YES' ? ' | null' : ''};\n`;
  }
  schema += `}\n\n`;
}
schema += `/** Row type of every core table. */\nexport interface CoreTables {\n${names.map((t) => `  ${t}: ${pascal(t)}Row;`).join('\n')}\n}\n\nexport type TableName = keyof CoreTables;\nexport type RowOf<T extends TableName> = CoreTables[T];\n\n`;
schema += `/** Columns and primary key of every core table (used to build safe SQL). */\nexport const TABLES: { [T in TableName]: { columns: readonly (keyof CoreTables[T] & string)[]; pk: readonly string[] } } = {\n`;
for (const t of names) {
  schema += `  ${t}: { columns: [${tables[t].columns.map((c) => q(c.column_name)).join(', ')}], pk: [${tables[t].pk.map(q).join(', ')}] },\n`;
}
schema += `};\n\nexport const TABLE_NAMES = Object.keys(TABLES) as TableName[];\n\n`;
schema += `/** Allowed values from CHECK constraints, e.g. VALUES.nodes.type. */\nexport const VALUES = ${JSON.stringify(enums, null, 2).replace(/"/g, "'")} as const;\n`;

let hooks = `// GENERATED by \`pnpm db:types\`. One hook per core table. Do not edit by hand.
// Each takes an optional filter of equal-to conditions, e.g. useAssets({ company_id: 'C001' }).
import { useTable, type Filter, type TableQueryOptions } from './hooks';

`;
for (const t of names) {
  hooks += `export const use${pascal(t)} = (filter?: Filter<'${t}'>, options?: TableQueryOptions) => useTable('${t}', filter, options);\n`;
}

fs.writeFileSync(path.join(here, '..', 'src', 'schema.gen.ts'), schema);
fs.writeFileSync(path.join(here, '..', 'src', 'hooks.gen.ts'), hooks);
const enumCount = Object.values(enums).reduce((n, e) => n + Object.keys(e).length, 0);
console.log(
  `Wrote schema.gen.ts and hooks.gen.ts: ${names.length} tables, ${columns.length} columns, ${enumCount} value lists.`,
);
