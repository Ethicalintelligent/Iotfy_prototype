// Design import (root CLAUDE.md §3a): takes the stylesheet of a developer-provided HTML page and
// scopes it under one class, so the page's own look can be used by React screens without
// leaking into the IoTIFY shell (sidebar, header) or other applications.
//
//   node tools/design-import/scope-css.cjs <page.html | page.css> <out.css> <scope-class>
//
// - Reads every <style> block of an .html file (or a whole .css file).
// - `:root`, `html` and `body` become the scope class itself (tokens and page background then
//   live on the wrapper element); every other selector is prefixed with it.
// - @keyframes and @font-face stay as they are. Nothing else is changed: same rules, same order.
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '../..');
// postcss comes with Vite (no extra dependency).
const vite = require.resolve('vite/package.json', {
  paths: [path.join(root, 'apps/customer-apps'), root],
});
const postcss = require(require.resolve('postcss', { paths: [path.dirname(vite)] }));

const [input, output, scope] = process.argv.slice(2);
if (!input || !output || !scope) {
  console.error(
    'usage: node tools/design-import/scope-css.cjs <page.html|page.css> <out.css> <scope-class>',
  );
  process.exit(1);
}
const text = fs.readFileSync(input, 'utf8');
const css = input.endsWith('.html')
  ? // only the page's own stylesheets: those before its scripts (scripts may contain "<style>" text)
    [
      ...text
        .slice(0, text.search(/<script[\s>]/i) >= 0 ? text.search(/<script[\s>]/i) : undefined)
        .matchAll(/<style[^>]*>([\s\S]*?)<\/style>/g),
    ]
      .map((m) => m[1])
      .join('\n')
  : text;

const S = '.' + scope;
const ROOTISH = /^(?::root|html|body)(?=$|[\s.:#[>+~])/;

function scopeSelector(sel) {
  const s = sel.trim();
  if (!s) return s;
  // `html body`, `:root body`, `html.dark body` … : collapse leading root-like parts into the scope
  let rest = s;
  let matched = false;
  for (;;) {
    const m = ROOTISH.exec(rest);
    if (!m) break;
    matched = true;
    rest = rest.slice(m[0].length);
    // keep qualifiers that sit on the root element ([data-theme=dark], .dark, :not(...))
    const q = /^(?:\[[^\]]*\]|\.[\w-]+|:not\([^)]*\)|:where\([^)]*\)|:is\([^)]*\))*/.exec(rest)[0];
    if (q) {
      rest = rest.slice(q.length);
      if (!rest.trim()) return S + q;
      const next = rest.replace(/^\s+/, '');
      if (ROOTISH.test(next)) {
        rest = next;
        continue;
      }
      return S + q + rest;
    }
    const next = rest.replace(/^\s+/, '');
    if (!next) return S;
    if (ROOTISH.test(next)) {
      rest = next;
      continue;
    }
    return S + (/^[>+~]/.test(next) ? ' ' : ' ') + next;
  }
  if (matched) return S;
  return `${S} ${s}`;
}

const ast = postcss.parse(css);
ast.walkRules((rule) => {
  for (let p = rule.parent; p; p = p.parent) {
    if (p.type === 'atrule' && /keyframes$/i.test(p.name)) return;
  }
  rule.selectors = rule.selectors.map(scopeSelector);
});
fs.mkdirSync(path.dirname(output), { recursive: true });
const header = `/* Generated by tools/design-import/scope-css.cjs from ${path.basename(input)}: do not edit by hand. Scope: ${S} */\n`;
fs.writeFileSync(output, header + ast.toString());
console.log(`${output}: ${(fs.statSync(output).size / 1024).toFixed(0)} KB, scoped under ${S}`);
